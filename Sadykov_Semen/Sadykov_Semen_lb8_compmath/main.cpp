#include "jacobi_core.h"

int main() {
    // Устанавливаем локаль для корректного отображения символов (необязательно)
    setlocale(LC_ALL, "Russian");

    cout << "=== СВОБОДНЫЙ РЕЖИМ ВВОДА СЛУ ===" << endl;
    
    int n;
    cout << "Введите размерность квадратной матрицы (n): "; 
    if (!(cin >> n) || n <= 0) {
        cout << "Ошибка: Некорректный размер." << endl;
        return 0;
    }

    Matrix A(n, Vector(n));
    Vector b(n);

    cout << "Введите элементы матрицы A (" << n << "x" << n << ") построчно:" << endl;
    for(int i = 0; i < n; i++) {
        for(int j = 0; j < n; j++) {
            cin >> A[i][j];
        }
    }

    cout << "Введите вектор b (" << n << " значений):" << endl;
    for(int i = 0; i < n; i++) cin >> b[i];

    JacobiSolver solver;

    // --- ЭТАП 1: ПРОВЕРКА НА ВШИВОСТЬ (ВЫРОЖДЕННОСТЬ) ---
    cout << "\n[!] Анализ системы на наличие единственного решения..." << endl;
    MatrixStats stats = solver.analyzeMatrix(A);

    /* 
       ВНИМАНИЕ: Если stats.is_degenerate == true, значит Det = 0.
       В этом случае по вашему требованию мы ОТМЕНЯЕМ любые дальнейшие действия.
    */
    if (stats.is_degenerate) {
        cout << "--------------------------------------------------------" << endl;
        cout << "ОТМЕНА ОПЕРАЦИИ: Матрица системы является ВЫРОЖДЕННОЙ." << endl;
        cout << "Причина: Ранг матрицы (" << stats.rank << ") меньше размерности (" << n << ")." << endl;
        cout << "Математически невозможно найти единственное решение." << endl;
        cout << "--------------------------------------------------------" << endl;
        return 0; // Полный выход из программы
    }

    // --- ЭТАП 2: ЕСЛИ МАТРИЦА НЕВЫРОЖДЕННАЯ, ИДЕМ ДАЛЬШЕ ---
    cout << "-> Проверка пройдена: Матрица невырожденная (Ранг " << stats.rank << ")." << endl;
    cout << "-> Выделено памяти: " << stats.memory_bytes << " байт." << endl;
    cout << "-> Запуск итерационного процесса Якоби...\n" << endl;

    bool success = false;
    Vector x = solver.solve(A, b, success);

    if (success) {
        cout << "=== РЕЗУЛЬТАТ СХОДИМОСТИ ===" << endl;
        for(int i = 0; i < x.size(); i++) {
            cout << "x[" << i << "] = " << fixed << setprecision(6) << x[i] << endl;
        }
        cout << "Итоговая невязка (ошибка): " << solver.getResidual(A, x, b) << endl;
    } else {
        cout << "=== ОШИБКА СХОДИМОСТИ ===" << endl;
        cout << "Матрица невырожденная, но метод простых итераций не сошелся." << endl;
        cout << "Скорее всего, не выполнено условие диагонального преобладания." << endl;
        cout << "Рекомендуется использовать метод Гаусса." << endl;
    }

    return 0;
}